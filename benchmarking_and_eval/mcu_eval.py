def sample_frames(video_path: Path):
    import cv2
    video, frames = cv2.VideoCapture(str(video_path)), []
    while video.isOpened():
        ok, frame = video.read()
        if not ok:
            break
        frames.append(base64.b64encode(cv2.imencode(".jpg", frame)[1]).decode())
    video.release()
    picked = frames[0::25]                 # same sampling as MCU's batch_video_rating.py
    return frames[0::70] if len(picked) > 60 else picked


def cmd_judge(args):
    from openai import OpenAI
    client = OpenAI(base_url=args.judge_base_url) if args.judge_base_url else OpenAI()
    system = TURBO_PROMPT.read_text()
    videos = sorted((Path(args.out) / "judge").rglob("*.mp4"))
    print(f"{len(videos)} videos")
    for v in videos:
        out = v.with_suffix(".judge.json")
        if out.exists():
            continue
        task = v.parent.name
        criteria_file = TURBO_CRITERIA / f"{task}.txt"
        if not criteria_file.exists():
            print(f"no criteria for {task}, skipping")
            continue
        query = [
            {"role": "system", "content": system},
            {"role": "user", "content": f"The task name is {task.replace('_', ' ')} You should follow the "
                                        f"following grading criteria to score the performance of agents in "
                                        f"videos{criteria_file.read_text()}\nHere are the image frames of the video A "},
            {"role": "user", "content": [{"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{f}"}}
                                         for f in sample_frames(v)]},
        ]
        answer = client.chat.completions.create(model=args.judge_model, messages=query,
                                                temperature=0.5).choices[0].message.content
        scores = {}
        for key in JUDGE_KEYS:
            m = re.findall(rf"-\s*{re.escape(key)}:\s*(\d+)", answer)
            if m:
                scores[key] = int(m[-1])       # last match = the "Overall Scores" block
        out.write_text(json.dumps({"scores": scores, "answer": answer}, indent=1))
        print(f"{v.parent.parent.name}/{task}/{v.name}: {scores}", flush=True)
    cmd_summary(args)


# =========================================================================== summary
def cmd_summary(args):
    out = Path(args.out)
    seen_file = Path(args.gen_root) / "seen_tasks.json"
    seen = json.loads(seen_file.read_text()) if seen_file.exists() else None

    by_task = {}
    for f in (out / "episodes").glob("*/ep_*/result.json"):
        r = json.loads(f.read_text())
        by_task.setdefault(r["task"], []).append(r)

    reward, buckets = {}, {}
    for task, rs in sorted(by_task.items()):
        if task.startswith("turbo:"):
            continue
        valid = [r for r in rs if r["success"] is not None]
        rate = sum(r["success"] for r in valid) / len(valid) if valid else None
        reward[task] = {"episodes": len(valid), "success_rate": rate, "setup_errors": len(rs) - len(valid)}
        if rate is None:
            continue
        cat = category(task)
        tag = "all" if seen is None else ("seen" if valid[0].get("env_prompt") in seen else "unseen")
        buckets.setdefault(f"{cat}/{tag}", []).append(rate)
    by_category = {k: {"tasks": len(v), "mean_success": sum(v) / len(v)} for k, v in sorted(buckets.items())}

    turbo = {}
    for f in (out / "judge").rglob("*.judge.json"):
        diff, task = f.parent.parent.name, f.parent.name
        turbo.setdefault(f"{diff}/{task}", []).append(json.loads(f.read_text())["scores"])
    turbo_avg = {t: {k: round(sum(s.get(k, 0) for s in ss) / len(ss), 2) for k in JUDGE_KEYS} | {"videos": len(ss)}
                 for t, ss in sorted(turbo.items())}

    summary = {"reward_by_category": by_category, "reward_by_task": reward, "turbo_judge": turbo_avg}
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps(by_category, indent=1))
    print(f"full summary -> {out / 'summary.json'}")


