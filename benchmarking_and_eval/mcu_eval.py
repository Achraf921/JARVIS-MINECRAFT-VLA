# =========================================================================== task specs
def source_root(source: str, gen_root: Path) -> Path:
    return {"jv": JV_CONFIG, "gen": gen_root, "turbo": TURBO_CONFIG}[source]


def expand_tasks(specs, gen_root: Path):
    out = []
    for spec in specs:
        source, pattern = spec.split(":", 1)
        root = source_root(source, gen_root)
        matches = sorted(glob.glob(str(root / f"{pattern}.yaml")))
        names = [str(Path(m).relative_to(root).with_suffix("")) for m in matches]
        names = [n for n in names if Path(n).name != "base"]
        if not names:
            print(f"warning: no tasks match {spec} under {root}")
        out += [f"{source}:{n}" for n in names]
    return out


def category(task: str) -> str:
    source, path = task.split(":", 1)
    return "turbo" if source == "turbo" else path.split("/")[0]


def task_dirname(task: str) -> str:
    return task.replace(":", "__").replace("/", "__")


