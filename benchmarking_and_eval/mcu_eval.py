"""
Minecraft evaluation for our Qwen3-VL-2B JARVIS-VLA checkpoint: automatically scored tasks, MCU-turbo,
a VLM judge, and a video for every episode.

Task sources (a task spec is "<source>:<path>", and globs work, e.g. "gen:mine/*"):
  jv:     JarvisVLA's own configs (mine/mine_stone, kill/kill_zombie, craft/craft_crafting_table, smelt/iron_ingot)
  gen:    Route B, configs generated by `gen` from JarvisVLA's instruction library and recipes.
          Hundreds of mine/kill/craft/smelt tasks. Success comes from game events (reward > 0), so no judge is needed.
  turbo:  Route A, MCU-turbo (simple/*, hard/*, compositional/*). There's no reward signal: episodes run a fixed
          600 steps and the video is scored afterwards by `judge` (GPT-4o by default, using MCU's prompt + criteria).

Subcommands:
  gen      write Route B configs to --gen-root
  seen     read only the `label` column of the stage-3 train split from HF, to mark tasks seen vs unseen in training
  run      roll out episodes (Ray actors, one model copy each), record videos, write result.json per episode
  judge    VLM-score the MCU-turbo videos
  summary  aggregate everything on disk into summary.json

Typical session on the GPU box:
  export JARVISVLA_ROOT=../JarvisVLA MCU_ROOT=../MCU
  python mcu_eval.py gen
  python mcu_eval.py seen
  python mcu_eval.py run --ckpt models.nosync/phase3_final --tasks "jv:*/*" --episodes 3 --workers 4    # pipeline check
  python mcu_eval.py run --ckpt ... --tasks "gen:mine/*" "gen:kill/*" "gen:craft/*" "gen:smelt/*" --sample 200 --episodes 10
  python mcu_eval.py run --ckpt ... --tasks "turbo:simple/*" "turbo:hard/*" --episodes 3 --show-actions
  OPENAI_API_KEY=... python mcu_eval.py judge
  python mcu_eval.py summary
"""
