def resolve_ingredient(ing):
    if isinstance(ing, list):
        ing = ing[0]
    if "item" in ing:
        return ing["item"].split(":")[-1]
    tag = ing["tag"].split(":")[-1]
    if tag in TAG_MAP:
        return TAG_MAP[tag]
    if tag.endswith("_logs") or tag.endswith("_stems"):
        return tag[:-1]
    return None


def write_cfg(path: Path, cfg: dict):
    import yaml
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump({"defaults": ["base", "_self_"], **cfg}, sort_keys=False))


def gen_mine(name, out):
    if any(x in name for x in MINE_EXCLUDE):
        return False
    write_cfg(out / "mine" / f"{name}.yaml", {
        "task_conf": [{"name": "mine", "text": f"mine_block:{name}"}],
        "reward_conf": [{"event": "mine_block", "max_reward_times": 1, "reward": 1.0,
                         "objects": [name], "identity": f"mine {name}"}],
        "init_inventory": TOOLS,
        # a ring of the target block around the player, then clear the player's own column
        "command": [f"/fill ~-2 ~ ~-2 ~2 ~1 ~2 minecraft:{name}", "/fill ~ ~ ~ ~ ~1 ~ minecraft:air"],
    })
    return True


def gen_kill(name, out):
    if name in KILL_EXCLUDE:
        return False
    cmds = ["/replaceitem entity @s armor.head minecraft:diamond_helmet",
            "/replaceitem entity @s armor.chest minecraft:diamond_chestplate",
            "/replaceitem entity @s armor.legs minecraft:diamond_leggings",
            "/replaceitem entity @s armor.feet minecraft:diamond_boots"]
    if name in UNDEAD:   # undead burn in daylight
        cmds += ["/time set night", "/effect give @a night_vision 99999 250 true"]
    write_cfg(out / "kill" / f"{name}.yaml", {
        "task_conf": [{"name": "kill_entity", "text": f"kill_entity:{name}"}],
        "reward_conf": [{"event": "kill_entity", "max_reward_times": 1, "reward": 1.0,
                         "objects": [name], "identity": f"kill {name}"}],
        "mobs": [{"name": name, "number": 1, "range_x": [-2, 2], "range_z": [3, 8]}],
        "init_inventory": [{"slot": 0, "type": "diamond_sword", "quantity": 1}],
        "command": cmds,
    })
    return True


def gen_craft(name, recipe, out):
    if recipe["type"] == "minecraft:crafting_shaped":
        pattern = recipe["pattern"]
        counts = {}
        for row in pattern:
            for ch in row:
                if ch != " ":
                    counts[ch] = counts.get(ch, 0) + 1
        items = {}
        for ch, n in counts.items():
            item = resolve_ingredient(recipe["key"][ch])
            if item is None:
                return False
            items[item] = items.get(item, 0) + n
        needs_table = len(pattern) > 2 or any(len(r) > 2 for r in pattern)
    elif recipe["type"] == "minecraft:crafting_shapeless":
        items = {}
        for ing in recipe["ingredients"]:
            item = resolve_ingredient(ing)
            if item is None:
                return False
            items[item] = items.get(item, 0) + 1
        needs_table = len(recipe["ingredients"]) > 4
    else:
        return False

    inv = [{"slot": 9 + i, "type": item, "quantity": min(64, 2 * n)} for i, (item, n) in enumerate(items.items())]
    if needs_table:
        inv.append({"slot": 35, "type": "crafting_table", "quantity": 1})
    write_cfg(out / "craft" / f"{name}.yaml", {
        "task_conf": [{"name": "craft", "text": f"craft_item:{name}"}],
        "reward_conf": [{"event": "craft_item", "max_reward_times": 1, "reward": 1.0,
                         "objects": [name], "identity": f"craft {name}"}],
        "init_inventory": inv,
        "need_gui": True,
        "need_crafting_table": needs_table,
        "worker": "craft",
    })
    return True


def gen_smelt(name, recipe, out):
    ingredient = resolve_ingredient(recipe["ingredient"])
    if ingredient is None:
        return False
    write_cfg(out / "smelt" / f"{name}.yaml", {
        "task_conf": [{"name": name, "text": f"craft_item:{name}"}],
        "reward_conf": [{"event": "craft_item", "max_reward_times": 1, "reward": 1.0,
                         "objects": [name], "identity": name}],
        "init_inventory": [{"slot": 0, "type": "furnace", "quantity": 1},
                           {"slot": 20, "type": "coal", "quantity": 10},
                           {"slot": 14, "type": ingredient, "quantity": 10}],
        "need_furnace": True,
        "need_gui": True,
        "worker": "smelt",
    })
    return True


def cmd_gen(args):
    out = Path(args.gen_root)
    for cat in ["mine", "kill", "craft", "smelt"]:
        (out / cat).mkdir(parents=True, exist_ok=True)
        shutil.copy(JV_CONFIG / cat / "base.yaml", out / cat / "base.yaml")   # hydra `defaults: [base]`

    library = json.loads((JV_ASSETS / "instructions.json").read_text())
    stats = {c: 0 for c in ["mine", "kill", "craft", "smelt"]}
    for key in library:
        if key.startswith("mine_block:"):
            stats["mine"] += gen_mine(key.split(":", 1)[1], out)
        elif key.startswith("kill_entity:"):
            stats["kill"] += gen_kill(key.split(":", 1)[1], out)

    for f in sorted((JV_ASSETS / "recipes").glob("*.json")):
        recipe = json.loads(f.read_text())
        result = recipe.get("result")
        result = result if isinstance(result, str) else (result or {}).get("item", "")
        if result.split(":")[-1] != f.stem:          # skip alternative recipes like *_from_*
            continue
        if recipe.get("type") == "minecraft:smelting":
            stats["smelt"] += gen_smelt(f.stem, recipe, out)
        else:
            stats["craft"] += gen_craft(f.stem, recipe, out)
    print(f"generated: {stats}  ->  {out}")


# =========================================================================== seen vs unseen
def cmd_seen(args):
    import pyarrow.parquet as pq
    import pyarrow.compute as pc
    from huggingface_hub import HfFileSystem

    fs = HfFileSystem()
    files = sorted(fs.glob("datasets/CraftJarvis/minecraft-vla-sft/data/train-*.parquet"))
    counts = {}
    for i, f in enumerate(files):
        labels = pq.read_table(f, columns=["label"], filesystem=fs)["label"]   # one column only, not the images
        for row in pc.value_counts(pc.list_element(labels, 2)).to_pylist():
            counts[row["values"]] = counts.get(row["values"], 0) + row["counts"]
        print(f"{i + 1}/{len(files)} shards, {len(counts)} distinct tasks", flush=True)
    path = Path(args.gen_root) / "seen_tasks.json"
    path.write_text(json.dumps(dict(sorted(counts.items(), key=lambda kv: -kv[1])), indent=1))
    print(f"wrote {path}")


# =========================================================================== policy
class Policy:
    def __init__(self, ckpt: str, device: str = "cuda"):
        import torch
        from transformers import Qwen3VLForConditionalGeneration, AutoProcessor
        from jarvisvla.inference.action_mapping import OneActionTokenizer

        self.torch = torch
        self.processor = AutoProcessor.from_pretrained(ckpt)      # saved with our added special tokens
        self.tok = self.processor.tokenizer
        self.model = Qwen3VLForConditionalGeneration.from_pretrained(
            ckpt, dtype=torch.bfloat16, device_map=device).eval()
        self.temperature = 0.9
        self.im_end = self.tok.convert_tokens_to_ids("<|im_end|>")

        # our id -> their Qwen2-VL id, built from the token strings (fails loudly if a token is missing)
        self.to_qwen2 = {}
        for n in RESERVED_RANGE:
            s = f"<|reserved_special_token_{n}|>"
            i = self.tok.convert_tokens_to_ids(s)
            assert isinstance(i, int) and self.tok.convert_ids_to_tokens(i) == s, f"missing token {s}"
            self.to_qwen2[i] = QWEN2_RESERVED_OFFSET + n
        self.act_tok = OneActionTokenizer(tokenizer_type="qwen2_vl")

    def act(self, frame: np.ndarray, instruction: str):
        from PIL import Image
        torch = self.torch
        # identical to training: user text ends with "\nobservation: \n", image after it, no system turn
        text = ("<|im_start|>user\n" + instruction + "\nobservation: \n"
                "<|vision_start|><|image_pad|><|vision_end|><|im_end|>\n"
                "<|im_start|>assistant\n")
        batch = self.processor(text=[text], images=[Image.fromarray(frame.astype(np.uint8))],
                               return_tensors="pt").to(self.model.device)
        batch["pixel_values"] = batch["pixel_values"].to(torch.bfloat16)

        gen = dict(max_new_tokens=32, eos_token_id=self.im_end)
        if self.temperature > 0:
            gen.update(do_sample=True, temperature=self.temperature, top_p=0.99, top_k=0)
        else:
            gen.update(do_sample=False)
        with torch.no_grad():
            out = self.model.generate(**batch, **gen)

        new_ids = out[0, batch["input_ids"].shape[1]:].tolist()
        action = self.act_tok.decode([self.to_qwen2.get(i, i) for i in new_ids])[0]   # chunk size 1
        return action, self.tok.decode(new_ids)


# =========================================================================== episodes
def make_instruction(env_prompt: str, library: dict) -> str:
    natural = env_prompt.replace("_", " ").replace(":", " ")
    return random.choice(library.get(env_prompt, {"instruct": [natural]})["instruct"])


def load_hydra_cfg(root: Path, path: str):
    import hydra
    hydra.core.global_hydra.GlobalHydra.instance().clear()
    with hydra.initialize_config_dir(config_dir=str(root / Path(path).parent), version_base="1.3"):
        return hydra.compose(config_name=Path(path).name)


def rollout(env, policy, info, instruction, max_frames, stop_on_reward):
    success, steps, first_outputs = False, max_frames, []
    for t in range(max_frames):
        action, raw = policy.act(info["pov"], instruction)
        if t < 20:
            first_outputs.append(raw)
        obs, reward, terminated, truncated, info = env.step(action)
        if stop_on_reward and reward > 0:
            success, steps = True, t
            break
    if success:                   # 20 extra steps so the video shows the result, as in their eval
        for _ in range(20):
            action, _ = policy.act(info["pov"], instruction)
            obs, reward, terminated, truncated, info = env.step(action)
    return success, steps, first_outputs


def run_reward_episode(policy, root, path, out_dir, max_frames, show_actions, library):
    """jv / gen tasks: JarvisVLA protocol, success = reward event."""
    from minestudio.simulator import MinecraftSim
    from minestudio.simulator.entry import CameraConfig
    from minestudio.simulator.callbacks import (
        RecordCallback, RewardsCallback, TaskCallback, FastResetCallback,
        InitInventoryCallback, SummonMobsCallback, CommandsCallback,
    )
    from jarvisvla.evaluate.env_helper.craft_agent import CraftWorker
    from jarvisvla.evaluate.env_helper.smelt_agent import SmeltWorker

    cfg = load_hydra_cfg(root, path)
    callbacks = [
        FastResetCallback(biomes=cfg.candidate_preferred_spawn_biome,
                          random_tp_range=cfg.random_tp_range, start_time=cfg.start_time),
        TaskCallback(getattr(cfg, "task_conf", None)),
        RewardsCallback(getattr(cfg, "reward_conf", None)),
        InitInventoryCallback(cfg.init_inventory,
                              inventory_distraction_level=cfg.inventory_distraction_level,
                              equip_distraction_level="normal"),
        RecordCallback(record_path=out_dir, fps=30, show_actions=show_actions),
    ]
    # MineStudio bug: CommandsCallback with an empty list re-wraps an already-wrapped obs -> KeyError 'pov'
    if getattr(cfg, "command", None):
        callbacks.insert(4, CommandsCallback(list(cfg.command)))
    if cfg.mobs:
        callbacks.append(SummonMobsCallback(cfg.mobs))

    env = MinecraftSim(
        action_type="env", seed=cfg.seed,
        obs_size=cfg.origin_resolution, render_size=cfg.resize_resolution,
        camera_config=CameraConfig(**cfg.camera_config),
        preferred_spawn_biome=getattr(cfg, "preferred_spawn_biome", None),
        callbacks=callbacks,
    )
    obs, info = env.reset()

    # GUI tasks: scripted setup opens the crafting table / furnace / inventory before the model acts
    if getattr(cfg, "need_gui", False):
        worker = CraftWorker(env, if_discrete=True) if getattr(cfg, "worker", None) == "craft" \
            else SmeltWorker(env, if_discrete=True)
        try:
            if getattr(cfg, "need_crafting_table", False):
                worker.open_crating_table_wo_recipe()
            elif getattr(cfg, "need_furnace", False):
                worker.open_furnace_wo_recipe()
            else:
                worker._null_action(1)
                if not worker.info["isGuiOpen"]:
                    worker._call_func("inventory")
        except AssertionError as e:
            env.close()
            return {"success": None, "steps": -1, "error": str(e)}
        info = worker.info

    env.action_type = "agent"     # from here on, env.step takes the decoded {"buttons", "camera"} action
    env_prompt = cfg.task_conf[0]["text"]
    instruction = make_instruction(env_prompt, library)       # fixed for the whole episode
    success, steps, first = rollout(env, policy, info, instruction, max_frames, stop_on_reward=True)
    env.close()
    return {"env_prompt": env_prompt, "instruction": instruction, "success": success,
            "steps": steps, "first_outputs": first}


def run_turbo_episode(policy, path, out_dir, max_frames, show_actions):
    """MCU-turbo: setup commands + fixed-length episode, scored later by the VLM judge."""
    import yaml
    from minestudio.simulator import MinecraftSim
    from minestudio.simulator.entry import CameraConfig
    from minestudio.simulator.callbacks import RecordCallback, CommandsCallback

    cfg = yaml.safe_load((TURBO_CONFIG / f"{path}.yaml").read_text())
    env = MinecraftSim(
        action_type="env", obs_size=(640, 360), render_size=(640, 360),
        camera_config=CameraConfig(**CAMERA_CFG),
        callbacks=([CommandsCallback(cfg["custom_init_commands"])] if cfg.get("custom_init_commands") else [])
                  + [RecordCallback(record_path=out_dir, fps=30, show_actions=show_actions)],
    )
    obs, info = env.reset()
    env.action_type = "agent"
    instruction = cfg["text"].strip()
    _, steps, first = rollout(env, policy, info, instruction, max_frames, stop_on_reward=False)
    env.close()
    return {"instruction": instruction, "success": None, "steps": steps, "first_outputs": first}


# =========================================================================== parallel run
def make_worker_class():
    import ray

    @ray.remote
    class Worker:
        def __init__(self, ckpt, gen_root):
            self.ckpt, self.gen_root = ckpt, Path(gen_root)
            self.policy = None
            self.library = json.loads((JV_ASSETS / "instructions.json").read_text())

        def run(self, task, ep, out_root, max_frames, temperature, show_actions):
            if self.policy is None:
                self.policy = Policy(self.ckpt)              # loaded once per actor
            self.policy.temperature = temperature
            source, path = task.split(":", 1)
            out_dir = Path(out_root) / "episodes" / task_dirname(task) / f"ep_{ep:03d}"
            out_dir.mkdir(parents=True, exist_ok=True)
            if source == "turbo":
                res = run_turbo_episode(self.policy, path, out_dir, max_frames, show_actions)
                videos = sorted(out_dir.rglob("*.mp4"))
                if videos:   # MCU judge layout: judge/<difficulty>/<task_name>/<video>.mp4
                    difficulty, name = path.split("/", 1)
                    dst = Path(out_root) / "judge" / difficulty / name / f"ep_{ep:03d}.mp4"
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy(videos[-1], dst)
            else:
                res = run_reward_episode(self.policy, source_root(source, self.gen_root), path,
                                         out_dir, max_frames, show_actions, self.library)
            res.update(task=task, episode=ep, temperature=temperature)
            (out_dir / "result.json").write_text(json.dumps(res, indent=1))
            return res

    return Worker


def cmd_run(args):
    import ray

    gen_root = Path(args.gen_root)
    tasks = expand_tasks(args.tasks, gen_root)
    if args.sample and len(tasks) > args.sample:
        tasks = sorted(random.Random(args.seed).sample(tasks, args.sample))
    print(f"{len(tasks)} tasks")

    jobs = []
    for task in tasks:
        for ep in range(args.episodes):     # resume: skip episodes that already have a result.json
            if not (Path(args.out) / "episodes" / task_dirname(task) / f"ep_{ep:03d}" / "result.json").exists():
                jobs.append((task, ep))
    print(f"{len(jobs)} episodes to run")
    if not jobs:
        return cmd_summary(args)

    ray.init(runtime_env={"env_vars": {"PYTHONPATH": str(JV_ROOT)}})
    Worker = make_worker_class()
    n = min(args.workers, len(jobs))
    workers = [Worker.options(num_gpus=1.0 / n).remote(args.ckpt, str(gen_root)) for _ in range(n)]

    def submit(w):
        task, ep = jobs.pop(0)
        cat = category(task)
        mf = args.max_frames or MAX_FRAMES[cat]
        temp = args.temperature if args.temperature is not None else TEMPERATURE[cat]
        pending[w.run.remote(task, ep, args.out, mf, temp, args.show_actions)] = w

    pending, total, done = {}, len(jobs), 0
    for w in workers:
        if jobs:
            submit(w)
    while pending:
        [ref], _ = ray.wait(list(pending), num_returns=1)
        w = pending.pop(ref)
        done += 1
        try:
            r = ray.get(ref)
            print(f"[{done}/{total}] {r['task']} ep {r['episode']}: success={r['success']} steps={r['steps']}",
                  flush=True)
        except Exception as e:          # one crashed episode shouldn't kill the run
            print(f"[{done}/{total}] episode failed: {e}", flush=True)
        if jobs:
            submit(w)
    cmd_summary(args)


